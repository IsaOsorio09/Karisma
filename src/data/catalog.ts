export function formatCOP(value: number): string {
  return new Intl.NumberFormat('es-CO', {
    style: 'currency',
    currency: 'COP',
    maximumFractionDigits: 0,
  }).format(value);
}

function normalizeGeoText(text: string): string {
  return text
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

/**
 * Calcula el domicilio únicamente cuando el cliente ha ingresado
 * tanto su municipio/ciudad como su dirección exacta.
 */
export function calculateShipping(
  municipality: string,
  address: string
): ShippingQuote | null {
  const cleanMunicipality = normalizeGeoText(municipality);
  const cleanAddress = address.trim();

  if (!cleanMunicipality || !cleanAddress) {
    return null;
  }

  const metroZona1 = ['medellin', 'envigado', 'itagui', 'sabaneta', 'bello'];
  const metroZona2 = ['caldas', 'la estrella', 'niquia'];

  if (metroZona1.includes(cleanMunicipality)) {
    return {
      cost: 10000,
      zoneName: 'Área Metropolitana (Zona Central)',
      estimatedDelivery: 'Entrega en 24 horas hábiles',
    };
  }

  if (metroZona2.includes(cleanMunicipality)) {
    return {
      cost: 13000,
      zoneName: 'Área Metropolitana (Zona Extendida)',
      estimatedDelivery: 'Entrega en 24 a 48 horas hábiles',
    };
  }

  return {
    cost: 18000,
    zoneName: 'Envío Nacional / Fuera del Valle de Aburrá',
    estimatedDelivery: 'Entrega de 2 a 4 días hábiles',
  };
}

export function buildWhatsAppOrderUrl(
  items: CartItem[],
  form: CheckoutFormData,
  subtotal: number,
  shipping: ShippingQuote
): string {
  const total = subtotal + shipping.cost;
  const productLines = items
    .map(
      (item, index) =>
        `${index + 1}. *${item.product.name}* (${item.product.brand})\n   • Cantidad: ${item.quantity} | Unitario: ${formatCOP(item.product.price)} | Subtotal: ${formatCOP(item.product.price * item.quantity)}`
    )
    .join('\n');

  const complementLine = form.apartmentComplement.trim()
    ? `\n• Apto / Casa / Interior: ${form.apartmentComplement.trim()}`
    : '';

  const message = `¡Hola *Karisma Face & Body*! Quiero confirmar mi nuevo pedido:

*DETALLE DE PRODUCTOS*
${productLines}

*RESUMEN DE PAGO*
• Subtotal productos: ${formatCOP(subtotal)}
• Domicilio (${shipping.zoneName}): ${formatCOP(shipping.cost)}
• *Total a pagar: ${formatCOP(total)}*

*DATOS DE ENTREGA*
• Nombre: ${form.fullName.trim()}
• Celular: ${form.phone.trim()}
• Departamento: ${form.department.trim()}
• Municipio / Ciudad: ${form.municipality.trim()}
• Dirección: ${form.address.trim()}${complementLine}

Quedo atenta para confirmar mi envío. ¡Muchas gracias!`;

  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(message)}`;
}
